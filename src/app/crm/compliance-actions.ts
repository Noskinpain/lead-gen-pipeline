"use server";

import { z } from "zod";
import { requireUser } from "@/lib/auth";
import { supabase } from "@/lib/supabase";
import { logger } from "@/lib/logger";
import { describeZodError, emptyToUndefined } from "@/lib/crm/form-helpers";
import { finish, type Outcome } from "@/lib/crm/action-helpers";
import { LAWFUL_BASES, MANUAL_SUPPRESSION_REASONS } from "@/lib/compliance/constants";
import { addSuppression } from "@/lib/compliance/suppression";

const RETURN_TO = "/crm/compliance";

// ---------- Record why we may contact someone ----------

const RecordBasisSchema = z.object({
  contactId: z.uuid(),
  basis: z.enum(LAWFUL_BASES),
  note: z.preprocess(emptyToUndefined, z.string().trim().max(500).optional()),
  collectedFrom: z.preprocess(emptyToUndefined, z.string().trim().max(300).optional()),
});

async function performRecordBasis(userId: string, input: z.infer<typeof RecordBasisSchema>): Promise<Outcome> {
  const note = input.note ?? "";

  if (input.basis !== "test_data" && note.length < 10) {
    return { ok: false, error: "Say how you know: the note is required (at least 10 characters)." };
  }
  if (input.basis === "legitimate_interest" && note.length < 30) {
    return { ok: false, error: "Legitimate interest needs a note that references your written assessment (at least 30 characters)." };
  }

  const now = new Date().toISOString();
  const { data: updated, error } = await supabase
    .from("contacts")
    .update({
      lawful_basis: input.basis,
      lawful_basis_note: note || null,
      lawful_basis_recorded_at: now,
      lawful_basis_recorded_by: userId,
      collected_from: input.collectedFrom ?? null,
      updated_at: now,
    })
    .eq("id", input.contactId)
    .select("id");

  if (error) {
    logger.error("recordLawfulBasis failed", { error: error.message });
    return { ok: false, error: "Could not save the basis." };
  }
  if (!updated || updated.length === 0) return { ok: false, error: "Contact not found." };

  return { ok: true, message: "Basis recorded." };
}

export async function recordLawfulBasis(formData: FormData): Promise<void> {
  const user = await requireUser();
  const parsed = RecordBasisSchema.safeParse(Object.fromEntries(formData));
  if (!parsed.success) finish(RETURN_TO, { ok: false, error: describeZodError(parsed.error) });
  finish(RETURN_TO, await performRecordBasis(user.id, parsed.data));
}

export async function markMockContactsAsTestData(): Promise<void> {
  const user = await requireUser();
  const now = new Date().toISOString();

  const { data, error } = await supabase
    .from("contacts")
    .update({
      lawful_basis: "test_data",
      lawful_basis_note: "Generated by the mock contact source",
      lawful_basis_recorded_at: now,
      lawful_basis_recorded_by: user.id,
      updated_at: now,
    })
    .is("lawful_basis", null)
    .eq("contact_source", "mock_contact_source")
    .select("id");

  if (error) {
    logger.error("markMockContactsAsTestData failed", { error: error.message });
    finish(RETURN_TO, { ok: false, error: "Could not update the contacts." });
  }
  finish(RETURN_TO, { ok: true, message: `${data?.length ?? 0} mock contacts marked as test data.` });
}

// ---------- Suppression list ----------

const AddSuppressionSchema = z.object({
  kind: z.enum(["email", "domain"]),
  value: z.string().trim().min(3).max(254),
  reason: z.enum(MANUAL_SUPPRESSION_REASONS),
});

const DOMAIN_PATTERN = /^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$/;

async function performAddSuppression(userId: string, input: z.infer<typeof AddSuppressionSchema>): Promise<Outcome> {
  if (input.kind === "email") {
    if (!z.email().safeParse(input.value).success) return { ok: false, error: "That isn't a valid email address." };
    const saved = await addSuppression({ email: input.value, reason: input.reason, source: "manual", createdById: userId });
    return saved.ok ? { ok: true, message: "Email suppressed." } : saved;
  }

  const domain = input.value.toLowerCase().replace(/^@/, "");
  if (!DOMAIN_PATTERN.test(domain)) return { ok: false, error: "That isn't a valid domain, for example example.com." };
  const saved = await addSuppression({ domain, reason: input.reason, source: "manual", createdById: userId });
  return saved.ok ? { ok: true, message: `Everyone at ${domain} is suppressed.` } : saved;
}

export async function addSuppressionEntry(formData: FormData): Promise<void> {
  const user = await requireUser();
  const parsed = AddSuppressionSchema.safeParse(Object.fromEntries(formData));
  if (!parsed.success) finish(RETURN_TO, { ok: false, error: describeZodError(parsed.error) });
  finish(RETURN_TO, await performAddSuppression(user.id, parsed.data));
}

const RemoveSuppressionSchema = z.object({
  id: z.uuid(),
  reason: z.string().trim().min(5).max(300),
});

export async function removeSuppressionEntry(formData: FormData): Promise<void> {
  const user = await requireUser();
  const parsed = RemoveSuppressionSchema.safeParse(Object.fromEntries(formData));
  if (!parsed.success) finish(RETURN_TO, { ok: false, error: "Say why it's OK to remove this (at least 5 characters)." });

  // Soft removal: the row stays, with who removed it and why.
  const { data: removed, error } = await supabase
    .from("suppressions")
    .update({ removed_at: new Date().toISOString(), removed_reason: parsed.data.reason, removed_by_id: user.id })
    .eq("id", parsed.data.id)
    .is("removed_at", null)
    .select("id");

  if (error) {
    logger.error("removeSuppression failed", { error: error.message });
    finish(RETURN_TO, { ok: false, error: "Could not remove the entry." });
  }
  if (!removed || removed.length === 0) finish(RETURN_TO, { ok: false, error: "That entry is already removed." });
  finish(RETURN_TO, { ok: true, message: "Entry removed." });
}